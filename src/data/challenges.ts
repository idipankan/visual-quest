export type Difficulty = 'easy' | 'medium' | 'hard'

export type VisionChallenge = {
  id: string
  title: string
  mission: string
  localizationPrompt: string
  difficulty: Difficulty
  basePoints: number
  hint: string
}

type ChallengeEntry = [id: string, title: string, mission: string, localizationPrompt: string, hint: string]

function challengesFor(difficulty: Difficulty, entries: ChallengeEntry[]): VisionChallenge[] {
  const basePoints = { easy: 100, medium: 150, hard: 190 }[difficulty]
  return entries.map(([id, title, mission, localizationPrompt, hint]) => ({
    id, title, mission, localizationPrompt, hint, difficulty, basePoints,
  }))
}

function moreChallengesFor(
  difficulty: Difficulty,
  entries: [title: string, target: string, hint: string][],
): VisionChallenge[] {
  return challengesFor(difficulty, entries.map(([title, target, hint]) => [
    `${difficulty}-${title.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-').replace(/-$/, '')}`,
    title,
    `Find ${target}.`,
    target,
    hint,
  ]))
}

